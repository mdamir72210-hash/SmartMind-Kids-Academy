const BENGALI_DIGITS = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];

export function toBengaliDigits(num: number): string {
  return String(num)
    .split('')
    .map((ch) => (ch >= '0' && ch <= '9' ? BENGALI_DIGITS[Number(ch)] : ch))
    .join('');
}

const ENGLISH_ONES = [
  '', 'One', 'Two', 'Three', 'Four', 'Five', 'Six', 'Seven', 'Eight', 'Nine',
  'Ten', 'Eleven', 'Twelve', 'Thirteen', 'Fourteen', 'Fifteen', 'Sixteen',
  'Seventeen', 'Eighteen', 'Nineteen',
];

const ENGLISH_TENS = [
  '', '', 'Twenty', 'Thirty', 'Forty', 'Fifty', 'Sixty', 'Seventy', 'Eighty', 'Ninety',
];

export function toEnglishNumberName(n: number): string {
  if (n === 100) return 'One Hundred';
  if (n < 20) return ENGLISH_ONES[n];
  const ten = Math.floor(n / 10);
  const one = n % 10;
  return one === 0 ? ENGLISH_TENS[ten] : `${ENGLISH_TENS[ten]}-${ENGLISH_ONES[one]}`;
}

